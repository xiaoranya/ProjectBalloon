function initialLocale(): AppLocale {
  if (typeof window === 'undefined' || !window.localStorage) return 'zh-CN';
  return window.localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh-CN';
}

const locale = ref<AppLocale>(initialLocale());

export function translate(key: string, params: Record<string, string | number> = {}): string {
  let value = locale.value === 'en' ? (english[key] ?? key) : key;
  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function setLocale(value: AppLocale) {
  locale.value = value;
  if (typeof document !== 'undefined') document.documentElement.lang = value;
  if (typeof window !== 'undefined' && window.localStorage) {
    window.localStorage.setItem(STORAGE_KEY, value);
  }
}

export function currentLocale(): AppLocale {
  return locale.value;
}

setLocale(locale.value);

export function useI18n() {
  return {
    locale: readonly(locale),
    elementLocale: computed(() => (locale.value === 'en' ? en : zhCn)),
    t: translate,
    setLocale,
  };
}
